<?php
/**
 * Frond vs the competition -- template rendering throughput (PHP).
 *
 * The gap this fills: benchmark_results.json measures only `json` and `list`, and
 * carbon_benchmarks.php measures Frond's template category against ITSELF in four
 * languages. Neither has ever timed Frond against the engine it replaces. Frond is
 * Twig-compatible, so Twig is the comparison that actually decides whether the
 * zero-dependency rewrite was worth shipping.
 *
 * Two things this harness does that a naive template benchmark does not:
 *
 * 1. IT PROVES THE ENGINES DO THE SAME WORK. Every engine renders the same page and
 *    the output is compared before anything is timed. Whitespace around block tags
 *    legitimately differs between engines, so the comparison collapses whitespace
 *    runs -- but raw byte lengths are printed too, so a suspicious difference stays
 *    visible instead of being normalised away. A mismatch ABORTS. Timing engines that
 *    emit different HTML is the most common way a template benchmark lies.
 *
 * 2. IT MEASURES STEADY STATE, NOT COMPILATION. Each engine's template is loaded ONCE
 *    outside the clock, then rendered repeatedly -- which is what a real app does per
 *    request. Calling Twig's createTemplate() inside the loop would recompile source to
 *    a PHP class on every iteration and report Twig as roughly an order of magnitude
 *    slower than it is. That is not a benchmark, it is a strawman.
 *
 * Deliberately avoided: `truncate` (needs twig/string-extra, not core Twig) and any
 * filter one engine lacks. The page sticks to constructs all three support natively --
 * variable output, a loop with index and even/odd, uppercase, 2-decimal number
 * formatting, and a conditional block.
 *
 * Competitor libraries live in this directory's composer.json, never the framework's.
 * Run: composer install && php bench_templates.php
 */

// TWO autoloaders on purpose. The framework's (one level up) provides Tina4\Frond and
// the classes it leans on (DotEnv, Log); this directory's provides Twig and Blade. That
// separation is the whole point: the competitors are never framework dependencies.
require __DIR__ . '/../vendor/autoload.php';
require __DIR__ . '/vendor/autoload.php';

/** Timed runs continue until this much wall-clock has elapsed. */
const MIN_SECONDS = 0.25;

/** ...but never fewer than this many iterations, however fast the engine. */
const MIN_ITERATIONS = 200;

/** The page data. 20 rows is a realistic list page, not a microbenchmark of one hole. */
function pageData(): array
{
    $items = [];
    for ($i = 0; $i < 20; $i++) {
        $items[] = ['name' => "Product {$i}", 'price' => $i * 9.99];
    }
    return [
        'title' => 'Benchmark Page',
        'heading' => 'Product List',
        'items' => $items,
        'show_footer' => true,
        'footer_text' => 'Generated by Tina4 Frond for the template throughput comparison.',
    ];
}

/**
 * Collapse whitespace runs so block-tag indentation differences between engines do
 * not register as output differences. Everything else must match exactly.
 */
function normalise(string $html): string
{
    return trim(preg_replace('/\s+/', ' ', $html));
}

/**
 * Time a render closure: p50 and mean ops/sec.
 *
 * Batched for the same reason the carbon suite batches -- a render is fast enough that
 * two hrtime() reads are a measurable fraction of the work, and a mean alone hides a
 * fat tail. Setup is outside the clock; only the render is timed.
 */
function measure(callable $render): array
{
    // Warm-up is a LOOP and runs twice: one pass still pays cold costs (autoload,
    // lazily-built caches, first compile), and reading a single cold op collapses the
    // batch size to 1, defeating the amortisation.
    $CALIBRATION_OPS = 64;
    $one = 1e-9;
    for ($pass = 0; $pass < 2; $pass++) {
        $t0 = hrtime(true);
        for ($i = 0; $i < $CALIBRATION_OPS; $i++) {
            $render();
        }
        $one = max((hrtime(true) - $t0) / 1e9 / $CALIBRATION_OPS, 1e-9);
    }

    $batch = min(max((int)(5e-5 / $one), 1), 10000);

    $batches = [];
    $iterations = 0;
    $start = hrtime(true);
    while (true) {
        $b0 = hrtime(true);
        for ($i = 0; $i < $batch; $i++) {
            $render();
        }
        $batches[] = ((hrtime(true) - $b0) / 1e9) / $batch;
        $iterations += $batch;
        $elapsed = (hrtime(true) - $start) / 1e9;
        if ($elapsed >= MIN_SECONDS && $iterations >= MIN_ITERATIONS) {
            break;
        }
    }

    sort($batches);
    $mid = intdiv(count($batches), 2);
    $p50 = count($batches) % 2 ? $batches[$mid] : ($batches[$mid - 1] + $batches[$mid]) / 2;
    $mean = array_sum($batches) / count($batches);

    return [
        'p50_ops_sec' => $p50 > 0 ? 1 / $p50 : 0,
        'mean_ops_sec' => $mean > 0 ? 1 / $mean : 0,
        'iterations' => $iterations,
        'batches' => count($batches),
    ];
}

$tmp = sys_get_temp_dir() . '/tina4_tpl_bench_' . getmypid();
@mkdir($tmp, 0777, true);
@mkdir("$tmp/blade_cache", 0777, true);

// --- Frond / Twig share one source. Frond is Twig-compatible, so this is the same
// --- bytes for both engines -- the fairest possible comparison of the two.
$frondTwigSource = <<<'TPL'
<!DOCTYPE html>
<html>
<head><title>{{ title }}</title></head>
<body>
<h1>{{ heading }}</h1>
<ul>
{% for item in items %}
<li class="{{ loop.index is even ? 'even' : 'odd' }}">{{ loop.index }}. {{ item.name|upper }} - ${{ item.price|number_format(2) }}</li>
{% endfor %}
</ul>
{% if show_footer %}
<footer>{{ footer_text }}</footer>
{% endif %}
</body>
</html>
TPL;

$bladeSource = <<<'TPL'
<!DOCTYPE html>
<html>
<head><title>{{ $title }}</title></head>
<body>
<h1>{{ $heading }}</h1>
<ul>
@foreach ($items as $item)
<li class="{{ $loop->iteration % 2 === 0 ? 'even' : 'odd' }}">{{ $loop->iteration }}. {{ strtoupper($item['name']) }} - ${{ number_format($item['price'], 2) }}</li>
@endforeach
</ul>
@if ($show_footer)
<footer>{{ $footer_text }}</footer>
@endif
</body>
</html>
TPL;

file_put_contents("$tmp/page.twig", $frondTwigSource);
file_put_contents("$tmp/page.blade.php", $bladeSource);

$data = pageData();
$engines = [];

// --- Frond (Tina4, zero dependencies) -------------------------------------------
$frond = new \Tina4\Frond($tmp);
$engines['Frond (Tina4)'] = fn() => $frond->render('page.twig', $data);

// --- Twig ------------------------------------------------------------------------
// A real filesystem cache, because real Twig deployments have one. Without it Twig
// recompiles the template to a PHP class on every render and the number is fiction.
$twig = new \Twig\Environment(
    new \Twig\Loader\FilesystemLoader($tmp),
    ['cache' => "$tmp/twig_cache", 'auto_reload' => false, 'debug' => false]
);
$twigTemplate = $twig->load('page.twig');   // compiled ONCE, outside the clock
$engines['Twig 3'] = fn() => $twigTemplate->render($data);

// --- Blade (illuminate/view) ------------------------------------------------------
$filesystem = new \Illuminate\Filesystem\Filesystem();
$resolver = new \Illuminate\View\Engines\EngineResolver();
$bladeCompiler = new \Illuminate\View\Compilers\BladeCompiler($filesystem, "$tmp/blade_cache");
$resolver->register('blade', fn() => new \Illuminate\View\Engines\CompilerEngine($bladeCompiler, $filesystem));
$viewFinder = new \Illuminate\View\FileViewFinder($filesystem, [$tmp]);
$factory = new \Illuminate\View\Factory($resolver, $viewFinder, new \Illuminate\Events\Dispatcher());
$factory->make('page', $data)->render();    // force the compile OUTSIDE the clock
$engines['Blade (Laravel)'] = fn() => $factory->make('page', $data)->render();

// --- Gate: every engine must emit the same page ------------------------------------
echo "\nTina4 Frond vs the competition -- template rendering (PHP " . PHP_VERSION . ")\n\n";
echo "  Output equivalence gate\n";
echo "  " . str_repeat('-', 72) . "\n";

$rendered = [];
foreach ($engines as $name => $render) {
    $rendered[$name] = $render();
}

$reference = null;
$referenceName = '';
$mismatch = false;
foreach ($rendered as $name => $html) {
    $norm = normalise($html);
    if ($reference === null) {
        $reference = $norm;
        $referenceName = $name;
        printf("    %-22s %6d bytes raw  (reference)\n", $name, strlen($html));
        continue;
    }
    $same = $norm === $reference;
    printf("    %-22s %6d bytes raw  %s\n", $name, strlen($html), $same ? 'IDENTICAL' : 'MISMATCH');
    if (!$same) {
        $mismatch = true;
        // Show where they diverge -- a silent normalise-and-move-on is how a benchmark
        // ends up comparing engines that render different pages.
        $len = min(strlen($norm), strlen($reference));
        $at = $len;
        for ($i = 0; $i < $len; $i++) {
            if ($norm[$i] !== $reference[$i]) { $at = $i; break; }
        }
        echo "      first difference at char {$at}:\n";
        echo "        {$referenceName}: ..." . substr($reference, max(0, $at - 40), 90) . "...\n";
        echo "        {$name}: ..." . substr($norm, max(0, $at - 40), 90) . "...\n";
    }
}

if ($mismatch) {
    echo "\n  ABORTED: the engines do not render the same page, so any timing below would\n";
    echo "  be comparing different work. Fix the templates before trusting a number.\n\n";
    exit(1);
}

echo "\n  All engines render the same page. Timing is meaningful.\n\n";

// --- Prove Frond is running its FASTEST path, not a fallback --------------------------
// Without this line the whole comparison is dismissable with "you benchmarked the
// interpreter". Frond has an AOT compiler (FrondCompiler, ADR-0001/0003) that turns the
// AST into a render closure, and it returns null and falls back to walking the AST for
// any construct it does not handle. Which path ran is invisible from the outside, so
// report it: a number measured on the fallback means something completely different.
$frondRef = new ReflectionClass($frond);
$compiledFnProp = $frondRef->getProperty('compiledFn');
$compiledFns = $compiledFnProp->getValue($frond);
$aotActive = false;
foreach ($compiledFns as $closure) {
    if ($closure !== null) { $aotActive = true; break; }
}
$debugMode = strtolower(getenv('TINA4_DEBUG') ?: '') === 'true';
echo "  Frond configuration (so the number cannot be dismissed)\n";
echo "  " . str_repeat('-', 72) . "\n";
printf("    AOT compiler (FrondCompiler)  %s\n", $aotActive ? 'ACTIVE - compiled render closure' : 'FALLBACK - walking the AST');
printf("    TINA4_DEBUG                   %s\n", $debugMode ? 'true (dev: re-reads + re-tokenizes every render)' : 'not true (production: template cache active)');
if (!$aotActive) {
    echo "\n    WARNING: Frond is on the interpreter fallback, so this measures the SLOW\n";
    echo "    path. Find which construct FrondCompiler rejected before quoting a ratio.\n";
}
echo "\n";

// --- Timing -----------------------------------------------------------------------
printf("  %-22s %13s %13s   %s\n", 'Engine', 'p50 ops/sec', 'mean ops/sec', 'samples');
echo "  " . str_repeat('-', 72) . "\n";

$results = [];
foreach ($engines as $name => $render) {
    $m = measure($render);
    $results[$name] = $m;
    printf(
        "  %-22s %13s %13s   %s\n",
        $name,
        number_format($m['p50_ops_sec'], 0),
        number_format($m['mean_ops_sec'], 0),
        number_format($m['iterations'], 0) . 'x' . $m['batches']
    );
}

$frondP50 = $results['Frond (Tina4)']['p50_ops_sec'];
echo "\n  Relative to Frond (p50):\n";
foreach ($results as $name => $m) {
    if ($name === 'Frond (Tina4)') continue;
    $ratio = $m['p50_ops_sec'] > 0 ? $frondP50 / $m['p50_ops_sec'] : INF;
    printf("    Frond is %.2fx %s than %s\n", $ratio >= 1 ? $ratio : 1 / $ratio, $ratio >= 1 ? 'faster' : 'SLOWER', $name);
}

file_put_contents(
    __DIR__ . '/template_comparison.json',
    json_encode([
        'language' => 'php',
        'runtime' => 'PHP ' . PHP_VERSION,
        'page' => ['items' => 20, 'engines' => array_keys($engines)],
        'output_equivalence' => 'verified',
        'results' => $results,
    ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n"
);

echo "\n  Wrote template_comparison.json\n";
echo "\n  Note: steady-state render only. Every engine's template is loaded and compiled\n";
echo "  ONCE outside the clock, matching how an app serves a page. Cold-start compile\n";
echo "  cost is a separate question and is NOT measured here.\n\n";

// Cleanup
$it = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($tmp, FilesystemIterator::SKIP_DOTS),
    RecursiveIteratorIterator::CHILD_FIRST
);
foreach ($it as $f) {
    $f->isDir() ? @rmdir($f->getPathname()) : @unlink($f->getPathname());
}
@rmdir($tmp);
