    /**
     * Boot the real dev-MCP server and invoke EVERY registered tool. Records each
     * result and asserts none threw — this alone catches the ArgumentCountError
     * throwers (migration_create/run) if a self-catch is removed.
     *
     * @return array<string, mixed> tool name => raw return value
     */
    private function invokeEveryTool(McpServer $server): array
    {
        $argMap = $this->toolArgs();
        $results = [];
        $threw = [];
        $missingArgs = [];

        foreach ($server->getToolList() as $tool) {
            $name = $tool['name'];
            if (!array_key_exists($name, $argMap)) {
                $missingArgs[] = $name;
            }
            try {
                $results[$name] = $server->callTool($name, $argMap[$name] ?? []);
            } catch (\Throwable $e) {
                $threw[$name] = get_class($e) . ': ' . $e->getMessage()
                    . ' @ ' . $e->getFile() . ':' . $e->getLine();
            }
        }

        $this->assertSame(
            [],
            $missingArgs,
            'New dev tool(s) with no args in the conformance map: ' . implode(', ', $missingArgs)
        );
        $this->assertSame(
            [],
            $threw,
            "Dev tool(s) threw an uncaught Throwable:\n" . implode("\n", array_map(
                fn($k, $v) => "  {$k} -> {$v}",
                array_keys($threw),
                array_values($threw)
            ))
        );

        return $results;
    }

    public function testEveryDevToolInvokesWithoutThrowing(): void
    {
        $server = new McpServer('/__dev/mcp', 'Tina4 Dev Tools');
        McpDevTools::register($server);

        // Registry is the source of truth — assert we actually enumerated the
        // whole toolkit (not a stale hardcoded subset).
        $names = array_column($server->getToolList(), 'name');
        $this->assertGreaterThanOrEqual(49, count($names), 'Dev toolkit shrank below 49 tools');
        $this->assertContains('migration_run', $names);
        $this->assertContains('database_execute', $names);

        $results = $this->invokeEveryTool($server);
        $this->assertNotEmpty($results);
    }

    /**
     * The 7 tools the sweep found broken must now return REAL success payloads:
     * not a stub info-string and not an {error} envelope.
     */
    public function testFixedToolsReturnRealPayloads(): void
    {
        $server = new McpServer('/__dev/mcp', 'Tina4 Dev Tools');
        McpDevTools::register($server);

        $r = $this->invokeEveryTool($server);

        // 1. migration_create — actually wrote a file on disk.
        $create = $r['migration_create'];
        $this->assertIsArray($create);
        $this->assertArrayNotHasKey('error', $create, 'migration_create returned {error}: ' . json_encode($create));
        $this->assertArrayHasKey('created', $create, 'migration_create did not report a created file: ' . json_encode($create));
        $this->assertFileExists($this->appRoot . '/migrations/' . $create['created']);

        // 2. migration_run — applied the real pending migration; the gadget table now exists.
        $run = $r['migration_run'];
        $this->assertIsArray($run);
        $this->assertArrayNotHasKey('error', $run, 'migration_run returned {error}: ' . json_encode($run));
        $this->assertArrayHasKey('applied', $run, 'migration_run did not return a migrate() result: ' . json_encode($run));
        $verifyDb = Database::create('sqlite:///' . $this->dbFile);
        $this->assertTrue($verifyDb->tableExists('gadget'), 'migration_run did not create the gadget table');

        // 3. route_test — dispatched the real route and returned a real response.
        $route = $r['route_test'];
        $this->assertIsArray($route);
        $this->assertArrayNotHasKey('error', $route, 'route_test returned {error}: ' . json_encode($route));
        $this->assertArrayNotHasKey('info', $route, 'route_test returned the old stub info-string: ' . json_encode($route));
        $this->assertSame(200, $route['status']);
        $this->assertStringContainsString('hi', $route['body']);
        $this->assertArrayHasKey('content_type', $route);

        // 4. seed_table — inserted N>0 real rows via the real seeder.
        $seed = $r['seed_table'];
        $this->assertIsArray($seed);
        $this->assertArrayNotHasKey('error', $seed, 'seed_table returned {error}: ' . json_encode($seed));
        $this->assertArrayNotHasKey('info', $seed, 'seed_table returned the old stub info-string: ' . json_encode($seed));
        // canonical cross-framework shape {table, inserted:<int>, failed:<int>}
        $this->assertArrayHasKey('inserted', $seed);
        $this->assertGreaterThan(0, $seed['inserted'], 'seed_table inserted no rows');
        $this->assertArrayHasKey('failed', $seed, 'seed_table missing the canonical failed count');
        $this->assertIsInt($seed['failed']);
        $seededCount = $verifyDb->fetch('SELECT COUNT(*) AS c FROM seed_target')->records[0]['c'];
        $this->assertGreaterThan(0, (int) $seededCount, 'seed_target has no rows after seed_table');

        // 5. error_log — returned the REAL tracked error (not the [] stub).
        $errors = $r['error_log'];
        $this->assertIsArray($errors);
        $this->assertNotEmpty($errors, 'error_log returned an empty list despite a captured error');
        $messages = array_column($errors, 'message');
        $this->assertContains('boom from conformance test', $messages, 'error_log did not surface the captured error: ' . json_encode($errors));

        // 6. queue_status — returned real counts (a job is pending).
        $queue = $r['queue_status'];
        $this->assertIsArray($queue);
        $this->assertArrayNotHasKey('error', $queue, 'queue_status returned {error}: ' . json_encode($queue));
        $this->assertSame('default', $queue['topic']);
        $this->assertGreaterThanOrEqual(1, $queue['pending'], 'queue_status did not see the pending job');

        // 7. database_execute — returned the TRUE affected-row count (was hardcoded 0).
        $exec = $r['database_execute'];
        $this->assertIsArray($exec);
        $this->assertArrayNotHasKey('error', $exec, 'database_execute returned {error}: ' . json_encode($exec));
        $this->assertTrue($exec['success']);
        $this->assertSame(1, $exec['affected_rows'], 'database_execute reported the wrong affected-row count: ' . json_encode($exec));
    }

    /**
     * migration_create refuses to spawn a duplicate for a slug that already
     * exists — it points the caller at the existing file instead (Python parity).
     */
    public function testMigrationCreateGuardsDuplicateSlug(): void
    {
        $server = new McpServer('/__dev/mcp', 'Tina4 Dev Tools');
        McpDevTools::register($server);

        $first = $server->callTool('migration_create', ['description' => 'create orders table']);
        $this->assertArrayHasKey('created', $first);

        $dup = $server->callTool('migration_create', ['description' => 'create orders table']);
        $this->assertIsArray($dup);
        $this->assertArrayHasKey('error', $dup, 'duplicate migration_create was not blocked: ' . json_encode($dup));
        $this->assertArrayHasKey('existing', $dup);
        $this->assertNotEmpty($dup['existing']);
    }
