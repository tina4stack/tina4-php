/**
 * Invoke-every-tool conformance test for the built-in dev-MCP toolkit.
 *
 * The prior MCP tool test only checked REGISTRATION (names present). That let 7
 * tools ship functionally broken — they self-caught into {error} or returned a
 * stub info-string, so a registration-only test stayed green. This test boots a
 * REAL throwaway app (real file SQLite DB, a real route, a real ORM model, a real
 * pending migration, real plans), builds the real dev-MCP server, enumerates
 * EVERY registered tool FROM THE REGISTRY (nothing hardcoded), and:
 *
 *   1. invokes each tool via callTool() and asserts NONE throws (catches the
 *      ArgumentCountError-class throwers if a self-catch is ever removed), AND
 *   2. asserts the 7 fixed tools return REAL success payloads — not a stub
 *      info-string and not an {error} envelope.
 *
 * No mocks: every dependency (SQLite, the queue file backend, the router, the
 * migration runner, the error store, the plan store) is the real thing.
 */
class McpDevToolsConformanceTest extends TestCase
{
    private string $appRoot = '';
    private string $oldCwd = '';
    private string $dbFile = '';

    /** @var array<string, string> env keys set for the run, restored in tearDown */
    private array $savedEnv = [];

    protected function setUp(): void
    {
        $this->oldCwd = getcwd() ?: '';
        $this->appRoot = sys_get_temp_dir() . '/tina4_mcp_conformance_' . uniqid('', true);
        $this->dbFile = $this->appRoot . '/app.db';

        foreach ([
            'src/orm', 'src/routes', 'src/templates', 'src/public',
            'migrations', 'plan', 'data/sessions', 'logs',
        ] as $dir) {
            @mkdir($this->appRoot . '/' . $dir, 0755, true);
        }

        $this->setEnv('TINA4_DATABASE_URL', 'sqlite:///' . $this->dbFile);
        $this->setEnv('TINA4_DEBUG', 'true');
        $this->setEnv('TINA4_MCP', 'true');
        $this->setEnv('TINA4_AUTO_MIGRATE', 'false');   // migration_run is what applies migrations here
        $this->setEnv('TINA4_QUEUE_BACKEND', 'file');   // deterministic, no external service

        // composer.json so deps_list / file_read have a real target.
        file_put_contents($this->appRoot . '/composer.json', json_encode([
            'name' => 'tina4/conformance-fixture',
            'require' => ['php' => '>=8.2'],
        ], JSON_PRETTY_PRINT));

        // A real ORM model (global namespace, filename == class) so orm_describe
        // has a model to describe. Distinctive name to avoid cross-test clashes.
        if (!class_exists('ConformanceWidget')) {
            file_put_contents($this->appRoot . '/src/orm/ConformanceWidget.php', <<<'PHP'
<?php
class ConformanceWidget extends \Tina4\ORM {
    public string $tableName = "widget";
    public string $primaryKey = "id";
}
PHP);
            require $this->appRoot . '/src/orm/ConformanceWidget.php';
        }

        // A route file target for file_patch (pre-created so file_patch works
        // regardless of loop order; file_write overwrites it in the same pass).
        file_put_contents(
            $this->appRoot . '/src/routes/probe_generated.php',
            "<?php\n// generated by probe\nreturn function () { return 'ok'; };\n"
        );

        // A real, pending migration with real DDL — migration_run must apply it.
        file_put_contents(
            $this->appRoot . '/migrations/000001_create_gadget_table.sql',
            "CREATE TABLE IF NOT EXISTS gadget (id INTEGER PRIMARY KEY, label TEXT);\n"
        );

        // Real DB with real data, persisted to the file so each fromEnv() sees it.
        $db = Database::create('sqlite:///' . $this->dbFile);
        $db->execute('CREATE TABLE IF NOT EXISTS widget (id INTEGER PRIMARY KEY, name TEXT)');
        $db->execute("INSERT INTO widget (id, name) VALUES (1, 'alpha'), (2, 'beta')");
        // A dedicated no-primary-key seed target so seed_table inserts cleanly
        // (no PK collision with pre-existing rows).
        $db->execute('CREATE TABLE IF NOT EXISTS seed_target (label TEXT, amount INTEGER)');
        $db->commit();

        chdir($this->appRoot);

        // Bind the ORM to the throwaway DB so model-backed tools resolve it.
        \Tina4\ORM::bindDatabase(Database::create('sqlite:///' . $this->dbFile));

        // A real public route for route_test to drive through the real router.
        Router::get('/__conformance_hello', function ($request, $response) {
            return $response('hi');
        });

        // A real queued job so queue_status reports a real pending count.
        (new Queue(topic: 'default'))->push(['task' => 'conformance']);

        // A real tracked error so error_log returns real data (not a [] stub).
        // ErrorTracker lives in DevAdmin.php (not its own PSR-4 file); reference
        // DevAdmin so the autoloader loads that file and the class resolves.
        class_exists(\Tina4\DevAdmin::class);
        // clearAll() empties the in-memory store so this run starts clean without
        // touching the global error/exception handlers (reset() would pop them and
        // make the test "risky").
        ErrorTracker::clearAll();
        ErrorTracker::capture(
            'ConformanceProbeError',
            'boom from conformance test',
            "#0 conformance\n",
            __FILE__,
            __LINE__
        );

        // Real plans so plan_* tools have targets.
        $verify = Plan::create('conformance verify', 'prove the tools', ['step one', 'step two'], true);
        $archive = Plan::create('conformance archive', 'throwaway', ['x'], false);
        $this->verifyPlanName = $verify['name'] ?? 'conformance-verify.md';
        $this->archivePlanName = $archive['name'] ?? 'conformance-archive.md';
    }

    private string $verifyPlanName = '';
    private string $archivePlanName = '';

    protected function tearDown(): void
    {
        if ($this->oldCwd !== '') {
            chdir($this->oldCwd);
        }
        foreach ($this->savedEnv as $key => $prior) {
            if ($prior === null) {
                putenv($key);
                unset($_ENV[$key], $_SERVER[$key]);
            } else {
                putenv("{$key}={$prior}");
                $_ENV[$key] = $prior;
            }
        }
        ErrorTracker::clearAll();
        $this->rrmdir($this->appRoot);
    }

    private function setEnv(string $key, string $value): void
    {
        $this->savedEnv[$key] = getenv($key) === false ? null : getenv($key);
        putenv("{$key}={$value}");
        $_ENV[$key] = $value;
    }

    private function rrmdir(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        foreach (scandir($dir) ?: [] as $entry) {
            if ($entry === '.' || $entry === '..') {
                continue;
            }
            $path = $dir . '/' . $entry;
            is_dir($path) ? $this->rrmdir($path) : @unlink($path);
        }
        @rmdir($dir);
    }

